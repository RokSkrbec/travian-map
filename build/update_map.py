#!/usr/bin/env python3
"""Download today's map.sql from rog.x2.europe.travian.com and rebuild travian-regions.html.

map.sql is regenerated by Travian every day at midnight (server time, UTC), so run this
once a day after that. Region outlines (regions.json) come from the in-game region pages
and don't change, so they're reused as-is.

Usage:  python3 build/update_map.py            (downloads a fresh map.sql)
        python3 build/update_map.py map.sql    (uses a local copy instead)
"""
import datetime, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'travian-regions.html')
URL = 'https://rog.x2.europe.travian.com/map.sql'

S = r"'((?:[^'\\]|\\.)*)'"
ROW = re.compile(r"VALUES \((\d+),(-?\d+),(-?\d+),(\d+),(\d+)," + S + r",(\d+)," + S + r",(\d+)," + S +
                 r",(\d+),(?:NULL|" + S + r"),(TRUE|FALSE|NULL),(TRUE|FALSE|NULL),(TRUE|FALSE|NULL),(\d+)\);")
unescape = lambda s: re.sub(r"\\(.)", r"\1", s or '')


def load_sql():
    if len(sys.argv) > 1:
        return open(sys.argv[1], encoding='utf-8').read()
    # macOS curl uses the system certificate store (python.org builds of Python often have none)
    body = subprocess.run(['curl', '-fsSL', '--max-time', '60', '-A', 'Mozilla/5.0 (travian-region-map)', URL],
                          check=True, capture_output=True).stdout.decode('utf-8')
    if 'INSERT INTO' not in body:
        sys.exit('map.sql download did not look like map data (got %d bytes)' % len(body))
    return body


def parse(sql):
    villages, bad = [], 0
    for line in sql.splitlines():
        if not line.startswith('INSERT'):
            continue
        m = ROW.search(line)
        if not m:
            bad += 1
            continue
        g = m.groups()
        flags = (g[12] == 'TRUE') | ((g[13] == 'TRUE') << 1) | ((g[14] == 'TRUE') << 2)
        # [x, y, region, tribe, village, player, alliance, population, flags, victoryPoints]
        villages.append([int(g[1]), int(g[2]), unescape(g[11]), int(g[3]), unescape(g[5]),
                         unescape(g[7]), unescape(g[9]), int(g[10]), flags, int(g[15])])
    return villages, bad


def main():
    villages, bad = parse(load_sql())
    regions = json.load(open(os.path.join(HERE, 'regions.json')))
    data = {'regions': [{'id': int(k), 'n': r['n'], 'd': r['d']}
                        for k, r in sorted(regions.items(), key=lambda kv: int(kv[0]))],
            'v': villages}
    blob = json.dumps(data, separators=(',', ':'), ensure_ascii=False).replace('</', '<\\/')
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
    html = open(os.path.join(HERE, 'template.html'), encoding='utf-8').read()
    html = html.replace('__DATE__', stamp).replace('__DATA__', blob)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(html)
    print(f'{len(villages)} villages ({bad} unparsed lines) -> {os.path.normpath(OUT)}  [{stamp}]')


if __name__ == '__main__':
    main()
