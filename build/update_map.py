#!/usr/bin/env python3
"""Download today's map.sql from rog.x2.europe.travian.com and rebuild travian-regions.html.

map.sql is regenerated by Travian every day at midnight (server time, UTC), so run this
once a day after that. Region outlines (regions.json) come from the in-game region pages
and don't change, so they're reused as-is.

Each run also saves a compact snapshot of today's villages to history/YYYY-MM-DD.json
(the GitHub workflow commits it), and the page gets the last HISTORY_DAYS snapshots for the
Farms & changes tab: population per village and player per day, and what changed day to day.

Usage:  python3 build/update_map.py            (downloads a fresh map.sql, saves today's snapshot)
        python3 build/update_map.py map.sql    (uses a local copy instead; no snapshot is saved)
"""
import datetime, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'travian-regions.html')
HIST = os.environ.get('MAP_HISTORY_DIR') or os.path.join(HERE, '..', 'history')
HISTORY_DAYS = 8
URL = 'https://rog.x2.europe.travian.com/map.sql'

S = r"'((?:[^'\\]|\\.)*)'"
ROW = re.compile(r"VALUES \((\d+),(-?\d+),(-?\d+),(\d+),(\d+)," + S + r",(\d+)," + S + r",(\d+)," + S +
                 r",(\d+),(?:NULL|" + S + r"),(TRUE|FALSE|NULL),(TRUE|FALSE|NULL),(TRUE|FALSE|NULL),(\d+)\);")
unescape = lambda s: re.sub(r"\\(.)", r"\1", s or '')


def load_sql():
    if len(sys.argv) > 1:
        return open(sys.argv[1], encoding='utf-8').read()
    # macOS curl uses the system certificate store (python.org builds of Python often have none)
    body = subprocess.run(['curl', '-fsSL', '--max-time', '60', '-A', 'Mozilla/5.0 (travian-region-map)', URL],
                          check=True, capture_output=True).stdout.decode('utf-8')
    if 'INSERT INTO' not in body:
        sys.exit('map.sql download did not look like map data (got %d bytes)' % len(body))
    return body


def parse(sql):
    villages, bad = [], 0
    for line in sql.splitlines():
        if not line.startswith('INSERT'):
            continue
        m = ROW.search(line)
        if not m:
            bad += 1
            continue
        g = m.groups()
        flags = (g[12] == 'TRUE') | ((g[13] == 'TRUE') << 1) | ((g[14] == 'TRUE') << 2)
        # [x, y, region, tribe, village, player, alliance, population, flags, victoryPoints, villageId, playerId]
        villages.append([int(g[1]), int(g[2]), unescape(g[11]), int(g[3]), unescape(g[5]),
                         unescape(g[7]), unescape(g[9]), int(g[10]), flags, int(g[15]), int(g[4]), int(g[6])])
    return villages, bad


def snapshot_rows(villages):
    # one row per village: [villageId, x, y, playerId, tribe, population, village, player, alliance]
    return sorted([v[10], v[0], v[1], v[11], v[3], v[7], v[4], v[5], v[6]] for v in villages)


def save_snapshot(date, rows):
    os.makedirs(HIST, exist_ok=True)
    with open(os.path.join(HIST, date + '.json'), 'w', encoding='utf-8') as f:
        f.write('{"date":"%s","v":[\n' % date)   # one village per line keeps git's deltas small
        f.write(',\n'.join(json.dumps(r, separators=(',', ':'), ensure_ascii=False) for r in rows))
        f.write('\n]}\n')


def history(today, rows):
    """Last HISTORY_DAYS snapshots (today's from memory) -> dates, pop per village/player, change events."""
    snaps = []
    if os.path.isdir(HIST):
        for fn in sorted(os.listdir(HIST)):
            if re.fullmatch(r'\d{4}-\d{2}-\d{2}\.json', fn) and fn[:10] < today:
                snaps.append((fn[:10], json.load(open(os.path.join(HIST, fn), encoding='utf-8'))['v']))
    snaps = snaps[-(HISTORY_DAYS - 1):] + [(today, rows)]
    days = [{r[0]: r for r in v} for _, v in snaps]
    players = []                      # per day: playerId -> [population, alliance, name]
    for d in days:
        p = {}
        for r in d.values():
            e = p.setdefault(r[3], [0, r[8], r[7]]); e[0] += r[5]
        players.append(p)
    vpop = {vid: [d[vid][5] if vid in d else -1 for d in days] for vid in days[-1]}   # matched to villages by id in main()
    ppop = {uid: [p[uid][0] if uid in p else -1 for p in players] for uid in players[-1]}
    ev = []                           # [type, day, x, y, village, player, alliance, pop, tribe, extra]
    for i in range(1, len(days)):
        a, b, pa, pb = days[i - 1], days[i], players[i - 1], players[i]
        for vid, r in b.items():
            if vid not in a:
                ev.append(['new', i, r[1], r[2], r[6], r[7], r[8], r[5], r[4], 0 if r[3] in pa else 1])
            elif a[vid][3] != r[3]:
                o = a[vid]; ev.append(['conq', i, r[1], r[2], r[6], r[7], r[8], r[5], r[4], o[7] + (' [%s]' % o[8] if o[8] else '')])
        for vid, r in a.items():
            if vid not in b:
                ev.append(['gone', i, r[1], r[2], r[6], r[7], r[8], r[5], r[4], 0 if r[3] in pb else 1])
        for uid, e in pb.items():
            if uid in pa and pa[uid][1] != e[1]:
                ev.append(['ally', i, 0, 0, '', e[2], e[1], e[0], 0, pa[uid][1]])
    return {'dates': [d for d, _ in snaps], 'vp': vpop, 'pp': ppop, 'ev': ev}


def main():
    villages, bad = parse(load_sql())
    today = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d')
    rows = snapshot_rows(villages)
    if len(sys.argv) == 1:
        save_snapshot(today, rows)
    hist = history(today, rows)
    hist['vp'] = [hist['vp'][v[10]] for v in villages]   # same order as the village list
    regions = json.load(open(os.path.join(HERE, 'regions.json')))
    data = {'regions': [{'id': int(k), 'n': r['n'], 'd': r['d']}
                        for k, r in sorted(regions.items(), key=lambda kv: int(kv[0]))],
            'v': villages, 'h': hist}
    blob = json.dumps(data, separators=(',', ':'), ensure_ascii=False).replace('</', '<\\/')
    stamp = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%d %H:%M UTC')
    html = open(os.path.join(HERE, 'template.html'), encoding='utf-8').read()
    html = html.replace('__DATE__', stamp).replace('__DATA__', blob)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(html)
    print(f'{len(villages)} villages ({bad} unparsed lines), {len(hist["dates"])} days of history, '
          f'{len(hist["ev"])} changes -> {os.path.normpath(OUT)}  [{stamp}]')


if __name__ == '__main__':
    main()
